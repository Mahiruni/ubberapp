export function translateOperational(language: "en" | "am", text: string) {
  return language === "am" ? am[text] || text : text;
}

export function useOperationalTranslation() {
  const language = useContext(LanguageContext);
  return useCallback((text: string) => translateOperational(language, text), [language]);
}
